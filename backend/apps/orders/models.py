from django.db import models
from django.core.validators import MinValueValidator
import uuid


class Order(models.Model):
    """
    Order model with idempotency via client_order_id.
    Customer data is snapshot'd (not FK'd) for accounting integrity.
    """
    STATUS_CHOICES = [
        ('RECEIVED', 'Received'),
        ('MEASUREMENT_REVIEW', 'Measurement Review'),
        ('CONFIRMED_WITH_CLIENT', 'Confirmed with Client'),
        ('CUTTING', 'Cutting'),
        ('STITCHING', 'Stitching'),
        ('EMBELLISHMENT', 'Embellishment'),
        ('QC', 'Quality Control'),
        ('SHIPPED', 'Shipped'),
        ('DELIVERED', 'Delivered'),
        ('CANCELLED', 'Cancelled'),
    ]
    
    PAYMENT_METHOD_CHOICES = [
        ('COD', 'Cash on Delivery'),
        ('STRIPE', 'Stripe'),
    ]
    
    PAYMENT_STATUS_CHOICES = [
        ('PENDING', 'Pending'),
        ('PAID', 'Paid'),
        ('FAILED', 'Failed'),
        ('REFUNDED', 'Refunded'),
    ]
    
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    
    # Idempotency key — generated by frontend, unique constraint prevents duplicates
    client_order_id = models.UUIDField(unique=True, db_index=True)
    
    # Market & currency
    market = models.CharField(
        max_length=10,
        choices=[('PK', 'Pakistan'), ('INTL', 'International')],
        db_index=True
    )
    currency = models.CharField(
        max_length=3,
        choices=[('PKR', 'PKR'), ('GBP', 'GBP')],
    )
    
    # Customer snapshot (not FK — preserves historical accuracy)
    customer_first_name = models.CharField(max_length=100)
    customer_last_name = models.CharField(max_length=100)
    customer_email = models.EmailField()
    customer_phone = models.CharField(max_length=20)
    customer_whatsapp_opt_in = models.BooleanField(default=False)
    
    # Shipping address snapshot
    shipping_line1 = models.CharField(max_length=255)
    shipping_line2 = models.CharField(max_length=255, blank=True)
    shipping_city = models.CharField(max_length=100)
    shipping_postal_code = models.CharField(max_length=20, blank=True)
    shipping_country = models.CharField(max_length=2)
    
    # Financials
    subtotal = models.DecimalField(max_digits=10, decimal_places=2)
    shipping_cost = models.DecimalField(max_digits=10, decimal_places=2, default=0)
    total = models.DecimalField(max_digits=10, decimal_places=2)
    
    # Status & payment
    status = models.CharField(
        max_length=50,
        choices=STATUS_CHOICES,
        default='RECEIVED',
        db_index=True
    )
    payment_method = models.CharField(
        max_length=20,
        choices=PAYMENT_METHOD_CHOICES,
    )
    payment_status = models.CharField(
        max_length=20,
        choices=PAYMENT_STATUS_CHOICES,
        default='PENDING',
        db_index=True
    )
    
    # Metadata
    notes = models.TextField(blank=True, help_text="Internal notes for admin")
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['status', 'market']),
            models.Index(fields=['payment_status', 'market']),
            models.Index(fields=['customer_email']),
        ]

    def __str__(self):
        return f"Order {self.client_order_id} — {self.customer_first_name} {self.customer_last_name}"
    
    @property
    def has_bespoke_items(self):
        """Check if order contains any custom/bespoke items."""
        return self.items.filter(mode='CUSTOM').exists()


class OrderItem(models.Model):
    """
    Individual line item in an order.
    Bespoke measurements stored as JSONB for flexibility.
    """
    MODE_CHOICES = [
        ('STANDARD', 'Standard Ready-to-Wear'),
        ('CUSTOM', 'Custom Bespoke'),
    ]
    
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    order = models.ForeignKey(
        Order,
        on_delete=models.CASCADE,
        related_name='items'
    )
    
    # Line identification
    line_id = models.CharField(max_length=100, unique=True, db_index=True)
    mode = models.CharField(max_length=10, choices=MODE_CHOICES, db_index=True)
    sku = models.CharField(max_length=100, db_index=True)
    
    # Product snapshot
    product_id = models.UUIDField()
    product_name = models.CharField(max_length=255)
    product_slug = models.SlugField(max_length=255)
    
    # Fabric snapshot
    fabric_variant_id = models.UUIDField()
    fabric_variant_name = models.CharField(max_length=255)
    
    # Sizing (size for STANDARD, measurements JSON for CUSTOM)
    size = models.CharField(max_length=10, blank=True, null=True)
    measurements = models.JSONField(
        null=True,
        blank=True,
        help_text="Bespoke measurements as JSON: {unit, shirtLength, bust, shoulder, waist, hips, sleeveLength, armhole, specialNotes}"
    )
    
    # Pricing snapshot (locked at add-to-cart time)
    currency = models.CharField(max_length=3, choices=[('PKR', 'PKR'), ('GBP', 'GBP')])
    unit_price = models.DecimalField(max_digits=10, decimal_places=2)
    quantity = models.IntegerField(default=1, validators=[MinValueValidator(1)])

    class Meta:
        ordering = ['id']

    def __str__(self):
        return f"{self.sku} — {self.product_name} ({self.mode})"
    
    @property
    def line_total(self):
        return self.unit_price * self.quantity